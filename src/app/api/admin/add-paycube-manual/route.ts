import { createClient } from '@/lib/supabase/server'
import { NextResponse } from 'next/server'

export async function GET() {
  const supabase = createClient()

  const content = `# PayCube保守業務 オペレーション・ガイド

## 概要

PayCubeの保守業務が新体制（自社完結型）に移行しました。
コンラックス社への申込書送付は**廃止**されました。
今後はPayCube保守システムを直接操作して登録・更新を行います。

---

## ログイン情報

| 項目 | 内容 |
|------|------|
| **URL** | https://dist.paycube-service.com/paycube/customer_detail.php |
| **Login ID** | devicee |
| **Password** | devicee |

---

## コア業務フロー

### ルート①：保守更新（既存顧客）

1. ログイン後、画面下部「**保守期限**」セクションを確認
2. **「今月」「来月」「再来月」の3タブを必ず全確認**（更新漏れ防止）
3. 設置先名（青文字リンク）をクリック
4. 右側の「**登録**」ボタンをクリック
5. 「保守サービス内容」のプルダウンから該当プランを選択
6. 「**登録**」ボタンで完了

#### 現在プラン別の対応方針

| 現在のプラン | 顧客への連絡 | 自動更新 | システム操作 |
|------|------|------|------|
| **無償保守** | **必須⚠** 加入意思・希望プランを確認 | なし | 顧客希望のプランを選択し登録 |
| **有償保守** | 不要 | あり | 同じプランを選択・期間延長して登録 |

---

### ルート②：新規登録

1. メニューから「**新規登録**」を選択
2. 不明な入力値は進捗管理シート（Google Spreadsheet）を参照して補完

#### 顧客情報（必須項目）

- 設置先名（必須）
- 郵便番号（必須）
- 住所（必須）
- 電話（必須）
- 備考（旧販売先・旧担当者など）

#### 設置機器リスト（必須項目）

- 保守開始日（必須）
- 製品タイプ（必須）
- 硬質ユニットシリアルNo.（必須）
- 紙幣ユニットシリアルNo.（必須）

> **⚠ シリアルNo.が不明な場合は「999999999」（9桁）を入力する**

3. 全入力完了後、「**保守申請に進む**」をクリック
4. 無償保守の場合：初期状態で「無償保守」がセットされているため**変更不要**。そのまま「**申請**」ボタンをクリック

---

## 完了後の必須作業

> **⚠ 保守システムへの入力だけでは業務完了ではありません**

1. **進捗管理シートをK列まで入力する**
2. **野田さんへ連携する**

進捗管理シート：
https://docs.google.com/spreadsheets/d/107wEIMY-wiIcPg0K_cDfyVGajKoFmluto8wJdSbqeOg/edit?gid=849544635#gid=849544635

---

## エスカレーション基準

| ケース | 対応 |
|------|------|
| ✅ 通常の更新・新規登録 | 管理シート記入 → 野田へ連携 |
| ⚠️ 保守の途中解約・別プランへの切り替え | **自己判断せず → 吉井さんへエスカレーション** |
| 🔴 保守期間が切れた状態での「再加入」 | **システム登録不可 → 直ちに吉井さんへエスカレーション** |

---

## オペレーター完了チェックリスト

- [ ] 「今月」「来月」「再来月」の3タブを全確認したか？
- [ ] 無償→有償切り替えの場合、顧客へ加入意思と希望プランを連絡したか？
- [ ] 新規登録時、赤い必須項目マークに漏れはないか？
- [ ] 進捗管理シートのK列まで入力し、野田へ連携したか？

---

## 担当者

| 役割 | 担当者 |
|------|------|
| 日常業務（更新・新規登録） | 各オペレーター |
| 連絡・進捗管理 | 野田さん |
| 例外対応・エスカレーション先 | 吉井さん |
`

  const { error } = await supabase.from('manuals').insert({
    title: 'PayCube保守業務 オペレーション・ガイド',
    category: 'PayCube',
    content,
  })

  if (error) return NextResponse.json({ error: error.message }, { status: 500 })
  return NextResponse.json({ ok: true, message: 'PayCube保守マニュアル登録完了' })
}

-- テーブル作成（未作成の場合）
create table if not exists mail_templates (
  id uuid default gen_random_uuid() primary key,
  category text not null,
  name text not null,
  purpose text,
  subject text,
  to_address text,
  cc_address text,
  body text,
  notes text,
  sort_order integer default 0,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);
alter table mail_templates enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename='mail_templates' and policyname='authenticated users can all on mail_templates') then
    execute 'create policy "authenticated users can all on mail_templates" on mail_templates for all using (auth.role() = ''authenticated'') with check (auth.role() = ''authenticated'')';
  end if;
end $$;

-- 既存データ削除（再実行時）
truncate table mail_templates restart identity cascade;

